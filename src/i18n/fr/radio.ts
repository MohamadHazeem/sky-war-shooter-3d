  'Capt. Hal Brenner', 'Lt. Frank Doyle', 'Lt. Eli Stern', 'Lt. Ray Kessler', 'Sgt. Mendez', 'Sgt. Luis Mendez',
  'Sgt. Tom Gallo', 'Sgt. Reilly', 'Sgt. Price', 'Sgt. Walsh', 'Sgt. Dawson',
