const ELEV: Record<string, string> = { high: 'haut', low: 'bas', level: 'même niveau' };
const CLOCK = "(one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve) o'clock (high|low|level)";
const clockFr = (h: string, e: string) => `${HOURS[h]} ${ELEV[e]}`;

const SIDE: Record<string, string> = { left: 'gauche', right: 'droite' };

const RANKS: Record<string, string> = { 'Capt.': 'Cne', 'Lt.': 'Lt', 'Sgt.': 'Sgt', 'Maj.': 'Cdt', 'Col.': 'Col.' };
