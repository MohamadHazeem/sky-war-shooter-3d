#!/usr/bin/env node
// Arabic voice-over source: the Arabic subtitle of every recorded clip, plus how Chatterbox should
// speak it. Reads tools/voice/lines.json (the English clips), translates each clip's text with the
// game's own phrase tables (src/i18n, exactly what the subtitle shows in Arabic) and writes
// tools/voice/lines_ar.json:  { texts: { "<English clip text>": { text: "<Arabic subtitle>", say?: "<spoken>" } } }
// Then render the Arabic clips with generate.py:
//
//   node --experimental-strip-types tools/voice/arabic.mjs && python3 tools/voice/generate.py --lang ar
//
// `say` is the subtitle made speakable: digits spelled out in Arabic words, Latin aircraft
// designations and bomber names transliterated, dashes/ellipses turned into pauses (commas).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
globalThis.localStorage ??= { getItem: () => null, setItem() {}, removeItem() {} };
// Use Vite's module loader so auto-discovered phrase tables match the game.
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
let tx, setLang, spokenArabic;
try {
  ({ tx, setLang } = await server.ssrLoadModule('/src/i18n/index.ts'));
  ({ spokenArabic } = await server.ssrLoadModule('/src/audio/arabicSpoken.ts'));
} finally {
  await server.close();
}
setLang('ar');

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, 'lines.json');
const OUT = join(HERE, 'lines_ar.json');
const HOURS = ['one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine', 'ten', 'eleven', 'twelve'];
const LEVELS = ['high', 'level', 'low'];
const AR = /[؀-ۿ]/;
// crew-room {n}: ships lost, spelled out in English; Arabic counts ships (feminine) 3-9
const LOSS_AR = { Three: 'ثلاث', Four: 'أربع', Five: 'خمس', Six: 'ست', Seven: 'سبع', Eight: 'ثماني', Nine: 'تسع' };

const cfg = JSON.parse(readFileSync(SRC, 'utf8'));
// Match generate.py's extension groups as well as the base catalogue.
for (const name of readdirSync(join(HERE, 'lines.d')).filter((n) => n.endsWith('.json')).sort()) {
  const group = JSON.parse(readFileSync(join(HERE, 'lines.d', name), 'utf8'));
  const at = cfg.lines.findIndex((l) => l.group === 'briefings (tools/voice/briefings.mjs)');
  cfg.lines.splice(at < 0 ? cfg.lines.length : at, 0, ...group);
}
const texts = {};
const missing = [];

function put(en, ar) {
  if (!ar || ar === en || !AR.test(ar)) { missing.push(en); return; }
  const e = { text: ar };
  const say = spokenArabic(ar);
  if (say !== ar) e.say = say;
  texts[en] = e;
}

for (const line of cfg.lines) {
  if (!line.id) continue;
  if (!line.vars) { put(line.text, tx(line.text)); continue; }
  const [[key, values]] = Object.entries(line.vars);
  for (const v of values) {
    const en = line.text.replaceAll(`{${key}}`, v);
    let ar = tx(en);
    // runtime-filled templates (crew room): translate the template, then fill the Arabic value
    if (ar === en || !AR.test(ar)) ar = tx(line.text, { [key]: key === 'n' && LOSS_AR[v] ? LOSS_AR[v] : tx(v) });
    put(en, ar);
  }
}
for (const h of HOURS) for (const lv of LEVELS) put(`${h} o'clock ${lv}!`, tx(`${h} o'clock ${lv}`) + '!');

if (missing.length) {
  console.error(`${missing.length} clip texts have no Arabic in the phrase tables:`);
  for (const m of missing) console.error('  ' + m);
  process.exit(1);
}
const out = {
  _doc: 'GENERATED by tools/voice/arabic.mjs from lines.json + the src/i18n Arabic phrase tables. Do not edit by hand: fix the phrase table (subtitle) or src/audio/arabicSpoken.ts (pronunciation) and re-run.',
  texts,
};
writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
console.log(`${Object.keys(texts).length} Arabic clip texts written to tools/voice/lines_ar.json`);
